
"use strict";

// Corrected code: calculate the sum of numbers from 1 to 5.

let total = 0;

for (let i = 1; i <= 5; i++) {
    total += i;
}

console.log("Total:", total);

// Corrected code: check whether a number is even or odd.

const number = 8;

if (number % 2 === 0) {
    console.log(number + " is even");
} else {
    console.log(number + " is odd");
}

